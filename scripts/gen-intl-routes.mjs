// Rewrites src/lib/intlRoutes.generated.ts from the pages themselves: every
// French, German, Spanish and Korean feeling page, guide and story by the
// English page it was written from, and every Taglish page by its English
// twin. Run it after adding or renaming one: node scripts/gen-intl-routes.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const read = (path) => readFileSync(join(root, path), 'utf8');
const LANGS = ['fr', 'de', 'es', 'ko'];

/** Each top-level entry's slug, lang and pair, in file order. */
function entries(source) {
  const chunks = source.split(/^(?= {4}slug: ')/m).slice(1);
  return chunks.map((chunk) => ({
    slug: chunk.match(/^ {4}slug: '([^']+)'/)[1],
    lang: chunk.match(/^ {4}lang: '([^']+)'/m)?.[1],
    pair: chunk.match(/^ {4}pair: '([^']+)'/m)?.[1],
  }));
}

const filesIn = (dir) =>
  readdirSync(join(root, dir))
    .filter((name) => name.endsWith('.ts'))
    .map((name) => `${dir}/${name}`);

const pages = Object.fromEntries(LANGS.map((lang) => [lang, {}]));
const stories = Object.fromEntries(LANGS.map((lang) => [lang, {}]));
const taglish = {};

for (const file of [
  ...filesIn('src/lib/intl/feelings'),
  ...filesIn('src/lib/intl/guides'),
]) {
  for (const { slug, lang, pair } of entries(read(file))) {
    if (!LANGS.includes(lang) || !pair) throw new Error(`${file}: ${slug}`);
    pages[lang][pair] = slug;
  }
}
for (const file of filesIn('src/lib/intl/stories')) {
  for (const { slug, lang, pair } of entries(read(file))) {
    if (!LANGS.includes(lang) || !pair) throw new Error(`${file}: ${slug}`);
    stories[lang][pair] = slug;
  }
}
for (const file of [
  'src/lib/feelingPages.ts',
  'src/lib/guidePages.ts',
  ...filesIn('src/lib/blog').filter((name) => /\/(stories|translations)-/.test(name)),
]) {
  for (const { slug, lang, pair } of entries(read(file))) {
    if (lang === 'tl' && pair) taglish[slug] = pair;
  }
}

const out = `// Generated by scripts/gen-intl-routes.mjs from the pages themselves.
// Don't edit by hand: run node scripts/gen-intl-routes.mjs instead.
import type { IntlLang } from './i18n';

/** Each feeling page and guide, by the English page it was written from. */
export const INTL_PAGE_SLUGS: Record<IntlLang, Record<string, string>> = ${JSON.stringify(pages, null, 2)};

/** Each story, by the English story it was adapted from. */
export const INTL_STORY_SLUGS: Record<IntlLang, Record<string, string>> = ${JSON.stringify(stories, null, 2)};

/** Each Taglish feeling page, guide and story, by its English twin. */
export const TAGLISH_TO_ENGLISH: Record<string, string> = ${JSON.stringify(taglish, null, 2)};
`;
writeFileSync(join(root, 'src/lib/intlRoutes.generated.ts'), out);
console.log(
  'pages',
  LANGS.map((lang) => `${lang} ${Object.keys(pages[lang]).length}`).join(', '),
  '| stories',
  LANGS.map((lang) => `${lang} ${Object.keys(stories[lang]).length}`).join(', '),
  '| taglish',
  Object.keys(taglish).length
);
